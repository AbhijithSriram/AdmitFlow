// Site content (v1.1 FR-12): loaded once at start-up by ContentContext; edited at /admin/content.
export const contentApi = {
  // The response is cacheable for a minute; fresh skips the browser's copy (after an admin's save).
  get: ({ fresh = false } = {}) => apiClient.get('/api/content', fresh ? { params: { t: Date.now() } } : undefined),
}
// The brochure is generated by the server from the current content (a link, not an XHR).
export const BROCHURE_URL = `${apiClient.defaults.baseURL ?? ''}/api/content/brochure`

